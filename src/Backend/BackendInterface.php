<?php
/**
 * Backend adapter contract (contracts/backend.md, ADR-0009).
 *
 * @package NF
 */

declare(strict_types=1);

namespace NF\Backend;

defined( 'ABSPATH' ) || exit;

/**
 * The only way to read and write NF tables.
 */
interface BackendInterface {

	/**
	 * Backend name: 'mysql' or 'pgsql'.
	 *
	 * @return string
	 */
	public function name(): string;

	/**
	 * SQL dialect for this backend.
	 *
	 * @return DialectInterface
	 */
	public function dialect(): DialectInterface;

	/**
	 * Resolve a logical table name ('nf_int') to the physical one for the current site.
	 *
	 * @param string $logical Logical table name.
	 * @return string
	 */
	public function table( string $logical ): string;

	/**
	 * Run a SELECT with positional ? placeholders.
	 *
	 * @param string                        $sql    SQL.
	 * @param array<int|string,scalar|null> $params Bound values.
	 * @return array<int,array<string,scalar|null>>
	 */
	public function select( string $sql, array $params = array() ): array;

	/**
	 * Run a write statement with positional ? placeholders.
	 *
	 * @param string                        $sql    SQL.
	 * @param array<int|string,scalar|null> $params Bound values.
	 * @return int Affected rows.
	 */
	public function execute( string $sql, array $params = array() ): int;

	/**
	 * ID generated by the last insert.
	 *
	 * @return int
	 */
	public function insertId(): int;

	/**
	 * Run a callable in a transaction: commit on return, roll back on throw.
	 *
	 * @param callable $fn Work to do.
	 * @return mixed What $fn returns.
	 */
	public function transaction( callable $fn ): mixed;

	/**
	 * Whether the connection is alive.
	 *
	 * @return bool
	 */
	public function ping(): bool;

	/**
	 * Take a non-blocking named lock.
	 *
	 * @param string $name Lock name.
	 * @return bool
	 */
	public function tryLock( string $name ): bool;

	/**
	 * Release a named lock.
	 *
	 * @param string $name Lock name.
	 * @return void
	 */
	public function unlock( string $name ): void;
}
